-- FinFlow P1 monthly recurring rules and idempotent execution journal.
-- Applied to Neon production 2026-11-07 (synthetic idempotency QA passed).
CREATE TABLE IF NOT EXISTS public.recurring_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 title VARCHAR(120) NOT NULL,
 amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
 type VARCHAR(10) NOT NULL CHECK (type IN ('income','expense')),
 category_id BIGINT NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
 account_id BIGINT REFERENCES public.financial_accounts(id) ON DELETE RESTRICT,
 currency VARCHAR(3) NOT NULL DEFAULT 'COP' CHECK (currency = 'COP'),
 frequency VARCHAR(10) NOT NULL DEFAULT 'monthly' CHECK (frequency='monthly'),
 day_of_month INTEGER NOT NULL CHECK (day_of_month BETWEEN 1 AND 28),
 next_due_date DATE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_recurring_rules_due ON public.recurring_rules(active,next_due_date,user_id);
CREATE TABLE IF NOT EXISTS public.recurring_executions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rule_id BIGINT NOT NULL REFERENCES public.recurring_rules(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 occurrence_date DATE NOT NULL,
 transaction_id BIGINT REFERENCES public.transactions(id) ON DELETE SET NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_recurring_rule_occurrence UNIQUE (rule_id,occurrence_date)
);
CREATE INDEX IF NOT EXISTS ix_recurring_executions_owner ON public.recurring_executions(user_id,occurrence_date DESC);
