-- FinFlow · AEVQOR · wallet/account P1 rollout
-- Applied to Neon production on 2026-11-07; all historical transactions remain without account assignment.
CREATE TABLE IF NOT EXISTS public.financial_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 name VARCHAR(80) NOT NULL,
 account_type VARCHAR(20) NOT NULL CHECK (account_type IN ('cash','bank','savings','other')),
 currency VARCHAR(3) NOT NULL DEFAULT 'COP' CHECK (currency ~ '^[A-Z]{3}$'),
 opening_balance NUMERIC(15,2) NOT NULL DEFAULT 0,
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_financial_accounts_owner_name ON public.financial_accounts(user_id,LOWER(TRIM(name)));
CREATE INDEX IF NOT EXISTS ix_financial_accounts_owner ON public.financial_accounts(user_id,archived);
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS account_id BIGINT REFERENCES public.financial_accounts(id) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS ix_transactions_account_owner ON public.transactions(user_id,account_id,status);
CREATE TABLE IF NOT EXISTS public.account_transfers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 from_account_id BIGINT NOT NULL REFERENCES public.financial_accounts(id) ON DELETE RESTRICT,
 to_account_id BIGINT NOT NULL REFERENCES public.financial_accounts(id) ON DELETE RESTRICT,
 amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
 transfer_date DATE NOT NULL,
 note VARCHAR(255),
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT chk_account_transfers_different CHECK (from_account_id <> to_account_id)
);
CREATE INDEX IF NOT EXISTS ix_account_transfers_owner ON public.account_transfers(user_id,transfer_date DESC);
