-- FinFlow · AEVQOR · Phase 1: monthly expense budgets (COP)
-- Apply with Neon tested migration before deploying the backend.
CREATE TABLE IF NOT EXISTS public.monthly_budgets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  budget_year INTEGER NOT NULL CHECK (budget_year BETWEEN 2000 AND 2100),
  budget_month INTEGER NOT NULL CHECK (budget_month BETWEEN 1 AND 12),
  limit_amount NUMERIC(15,2) NOT NULL CHECK (limit_amount > 0),
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_monthly_budgets_owner_category_period
     UNIQUE (user_id,category_id,budget_year,budget_month)
);
CREATE INDEX IF NOT EXISTS idx_monthly_budgets_owner_period
  ON public.monthly_budgets (user_id,budget_year,budget_month);
CREATE INDEX IF NOT EXISTS idx_monthly_budgets_category
  ON public.monthly_budgets (category_id);
